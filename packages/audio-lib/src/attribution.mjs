// Attribution manifest: ATTRIBUTION.json (source of truth) + ATTRIBUTION.md
// (human-readable), kept next to the downloaded files and updated on every use.
import fs from 'node:fs/promises';
import path from 'node:path';

/** @typedef {import('./types.mjs').AudioResult} AudioResult */

/**
 * @typedef {object} ManifestEntry
 * @property {string} id
 * @property {string} title
 * @property {string} creator
 * @property {string | null} sourceUrl
 * @property {string} license
 * @property {string | null} licenseUrl
 * @property {boolean} requiresAttribution
 * @property {boolean} allowsCommercialUse
 * @property {string} attributionText
 * @property {string[]} files       file names relative to the manifest
 * @property {string} firstUsedAt
 * @property {string} lastUsedAt
 */

export const MANIFEST_JSON = 'ATTRIBUTION.json';
export const MANIFEST_MD = 'ATTRIBUTION.md';

/** @param {string} dir @returns {Promise<ManifestEntry[]>} */
export async function readManifest(dir) {
  try {
    const j = JSON.parse(await fs.readFile(path.join(dir, MANIFEST_JSON), 'utf8'));
    return Array.isArray(j.entries) ? j.entries : [];
  } catch {
    return [];
  }
}

/** Serializes manifest writes within this process. */
let queue = Promise.resolve();

/**
 * Record that `result` was downloaded/used as `file` (inside `dir`).
 * @param {string} dir @param {AudioResult} result @param {string} file
 * @returns {Promise<ManifestEntry[]>}
 */
export function recordUse(dir, result, file, now = new Date()) {
  const run = queue.then(async () => {
    const entries = await readManifest(dir);
    const at = now.toISOString();
    const name = path.relative(dir, file).split(path.sep).join('/');
    let e = entries.find((x) => x.id === result.id);
    if (!e) {
      e = {
        id: result.id,
        title: result.title,
        creator: result.creator,
        sourceUrl: result.sourceUrl,
        license: result.license,
        licenseUrl: result.licenseUrl,
        requiresAttribution: result.requiresAttribution,
        allowsCommercialUse: result.allowsCommercialUse,
        attributionText: result.attributionText,
        files: [],
        firstUsedAt: at,
        lastUsedAt: at,
      };
      entries.push(e);
    }
    e.lastUsedAt = at;
    if (!e.files.includes(name)) e.files.push(name);
    await fs.mkdir(dir, {recursive: true});
    await fs.writeFile(path.join(dir, MANIFEST_JSON), JSON.stringify({entries}, null, 2) + '\n');
    await fs.writeFile(path.join(dir, MANIFEST_MD), exportAttribution(entries, 'markdown'));
    return entries;
  });
  queue = run.then(() => undefined, () => undefined);
  return run;
}

/**
 * Export credits.
 * - 'text': one attribution line per item (credits screen / video description)
 * - 'markdown': full ATTRIBUTION.md
 * - 'json': the raw entries
 * Items that don't require attribution are still listed: crediting CC0 work is good practice.
 * @param {ManifestEntry[]} entries
 * @param {'text' | 'markdown' | 'json'} [format]
 */
export function exportAttribution(entries, format = 'text') {
  if (format === 'json') return JSON.stringify(entries, null, 2);
  if (format === 'text') {
    if (!entries.length) return '';
    return ['Music & sound effects:', ...entries.map((e) => `- ${e.attributionText}`)].join('\n') + '\n';
  }
  const lines = [
    '# Audio attribution',
    '',
    'Auto-generated by the LaunchReel audio library on every download. Do not edit by hand: changes are overwritten.',
    '',
  ];
  if (!entries.length) lines.push('_No audio used yet._');
  for (const e of entries) {
    lines.push(
      `## ${e.title}`,
      '',
      `- **Creator:** ${e.creator}`,
      `- **Source:** ${e.sourceUrl ?? 'n/a'}`,
      `- **License:** ${e.license}${e.licenseUrl ? ` (${e.licenseUrl})` : ''}`,
      `- **Commercial use:** ${e.allowsCommercialUse ? 'allowed' : 'NOT allowed / unverified'}`,
      `- **Attribution required:** ${e.requiresAttribution ? 'yes' : 'no'}`,
      `- **Files:** ${e.files.map((f) => `\`${f}\``).join(', ')}`,
      '',
      `> ${e.attributionText}`,
      '',
    );
  }
  return lines.join('\n');
}
